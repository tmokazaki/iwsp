"""
Core iWSP (Interpretable Weight-Space Programming) Agent Loop & Sandbox Harness
===============================================================================

Implements the iterative scientific workflow described in arXiv:2611.18114:
1. Hypothesis Generation: The LLM scientist proposes a mechanistic hypothesis for how
   explicit weights or feature transformations solve the target task.
2. Weight-Space / Feature-Space Code Construction: The agent writes explicit Python code
   defining a callable `build_model()` or `extract_features(stimuli)` function with
   human-readable comments and zero gradient-based training.
3. Validation Evaluation: The harness executes the generated code in an isolated namespace
   and evaluates it on held-out validation examples, returning scalar validation feedback
   and diagnostic summaries (without leaking target test labels).
4. Iterative Refinement: The agent inspects the trial history (hypotheses, code, scores,
   parameter counts, and interpretability audits) and refines the weight program.
"""

from __future__ import annotations

import abc
import json
import os
import re
import time
import traceback
import urllib.request
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Tuple


@dataclass
class IWSPTrial:
    """Record of a single iWSP iteration trial."""

    iteration: int
    hypothesis: str
    code: str
    val_score: float
    metrics: Dict[str, Any] = field(default_factory=dict)
    interpretation_summary: str = ""
    error: Optional[str] = None
    elapsed_ms: float = 0.0
    is_best: bool = False


@dataclass
class IWSPHarvester:
    """Result summary produced by an iWSP optimization run."""

    task_name: str
    domain: str
    best_trial: Optional[IWSPTrial]
    history: List[IWSPTrial]
    compiled_artifact: Any = None

    def summary_table(self) -> str:
        """Render a clean Markdown/ASCII table of the iWSP iterative discovery trajectory."""
        lines = [
            f"=== iWSP Trajectory: {self.task_name} ({self.domain}) ===",
            f"{'Iter':>4} | {'Score':>8} | {'Best':>4} | {'Status':<10} | Hypothesis",
            "-" * 88,
        ]
        for t in self.history:
            status = "ERROR" if t.error else "OK"
            best_mark = " ★ " if t.is_best else "   "
            hyp = (t.hypothesis[:45] + "...") if len(t.hypothesis) > 48 else t.hypothesis
            lines.append(f"{t.iteration:>4} | {t.val_score:>8.4f} | {best_mark:>4} | {status:<10} | {hyp}")
        if self.best_trial:
            lines.append("-" * 88)
            lines.append(
                f"Best Score: {self.best_trial.val_score:.4f} (Iter {self.best_trial.iteration})"
            )
            if self.best_trial.interpretation_summary:
                lines.append(f"Mechanistic Account: {self.best_trial.interpretation_summary}")
        return "\n".join(lines)


class SandboxExecutor:
    """
    Executes weight-space or feature-space Python code generated by an LLM agent
    in a controlled namespace and extracts the target entry point function.

    Enforces the core iWSP rule: NO gradient-based training (forbids `.backward()`,
    `torch.optim`, `scipy.optimize`, etc. inside weight construction programs).
    """

    FORBIDDEN_PATTERNS = [
        r"\.backward\s*\(",
        r"torch\.optim\b",
        r"tf\.GradientTape\b",
        r"optax\b",
        r"Loss\.backward",
    ]

    def __init__(self, extra_globals: Optional[Dict[str, Any]] = None) -> None:
        self.extra_globals = extra_globals or {}

    def verify_no_gradients(self, code: str) -> None:
        """Verify that the weight-space program does not use gradient descent."""
        for pattern in self.FORBIDDEN_PATTERNS:
            if re.search(pattern, code):
                raise ValueError(
                    f"iWSP Violation: Gradient-based optimization pattern '{pattern}' "
                    "is forbidden in weight-space programming."
                )

    def execute_and_extract(
        self, code: str, entrypoint: str = "build_model"
    ) -> Tuple[Callable[..., Any], Dict[str, Any]]:
        """
        Execute the Python source string and return `(entrypoint_callable, namespace)`.
        """
        self.verify_no_gradients(code)

        import math
        import iwsp.math_backend as mb
        from iwsp.transformers.architecture import (
            AttentionHeadWeights,
            MLPWeights,
            TransformerLayerWeights,
            TransparentTransformer,
        )

        namespace: Dict[str, Any] = {
            "__builtins__": __builtins__,
            "math": math,
            "mb": mb,
            "np": mb.np,
            "TransparentTransformer": TransparentTransformer,
            "TransformerLayerWeights": TransformerLayerWeights,
            "AttentionHeadWeights": AttentionHeadWeights,
            "MLPWeights": MLPWeights,
        }
        namespace.update(self.extra_globals)

        exec(compile(code, "<iwsp_weight_program>", "exec"), namespace)
        if entrypoint not in namespace or not callable(namespace[entrypoint]):
            raise KeyError(
                f"Generated weight-space program must define a callable `{entrypoint}(...)`."
            )
        return namespace[entrypoint], namespace


class LLMBackend(abc.ABC):
    """Abstract interface for an LLM Scientist agent in iWSP."""

    @abc.abstractmethod
    def propose_next_program(
        self,
        task_name: str,
        task_description: str,
        entrypoint: str,
        history: List[IWSPTrial],
        iteration: int,
    ) -> Tuple[str, str]:
        """
        Given the task specification and past trials, return `(hypothesis, python_code)`.
        """


class OfflineScientistBackend(LLMBackend):
    """
    Offline / Deterministic Scientist Backend for reproducible local execution without API keys.

    Replays a multi-step scientific refinement trajectory (from initial baseline hypothesis
    to intermediate refinement to final glass-box weight program) matching the discovery
    trajectories reported in arXiv:2611.18114.
    """

    def __init__(
        self,
        trajectories: Optional[Dict[str, List[Tuple[str, str]]]] = None,
    ) -> None:
        self.trajectories: Dict[str, List[Tuple[str, str]]] = trajectories or {}

    def register_trajectory(
        self, task_name: str, steps: List[Tuple[str, str]]
    ) -> None:
        """Register a list of `(hypothesis, code)` steps for a task."""
        self.trajectories[task_name] = steps

    def propose_next_program(
        self,
        task_name: str,
        task_description: str,
        entrypoint: str,
        history: List[IWSPTrial],
        iteration: int,
    ) -> Tuple[str, str]:
        if task_name in self.trajectories:
            steps = self.trajectories[task_name]
            idx = min(iteration - 1, len(steps) - 1)
            return steps[idx]
        raise KeyError(
            f"No offline trajectory registered for task '{task_name}'. "
            f"Available tasks: {list(self.trajectories.keys())}"
        )


class APIScientistBackend(LLMBackend):
    """
    Live LLM API Backend supporting OpenAI (`OPENAI_API_KEY`), Anthropic (`ANTHROPIC_API_KEY`),
    and Google Gemini (`GEMINI_API_KEY`) via standard HTTPS requests (zero external SDK deps).
    """

    SYSTEM_PROMPT = (
        "You are an expert mechanistic interpretability scientist performing "
        "Interpretable Weight-Space Programming (iWSP, arXiv:2611.18114).\n"
        "Your task is to construct neural network weights or brain encoding features "
        "DIRECTLY IN PYTHON CODE without any gradient-based training.\n"
        "Every neuron, attention head, embedding dimension, and feature transformation "
        "must have an explicit, human-understandable mechanistic purpose.\n\n"
        "Respond strictly in the following format:\n"
        "HYPOTHESIS: <1-2 sentences explaining your mechanistic hypothesis for this iteration>\n"
        "```python\n"
        "<valid Python code defining the requested entrypoint function>\n"
        "```"
    )

    def __init__(
        self,
        provider: str = "auto",
        model: Optional[str] = None,
        api_key: Optional[str] = None,
        temperature: float = 0.2,
    ) -> None:
        self.provider = self._resolve_provider(provider)
        self.api_key = api_key or self._resolve_api_key(self.provider)
        self.model = model or self._default_model(self.provider)
        self.temperature = temperature

    @staticmethod
    def _resolve_provider(provider: str) -> str:
        if provider != "auto":
            return provider.lower()
        if os.environ.get("GEMINI_API_KEY"):
            return "gemini"
        if os.environ.get("OPENAI_API_KEY"):
            return "openai"
        if os.environ.get("ANTHROPIC_API_KEY"):
            return "anthropic"
        return "openai"

    @staticmethod
    def _resolve_api_key(provider: str) -> str:
        env_map = {
            "gemini": "GEMINI_API_KEY",
            "openai": "OPENAI_API_KEY",
            "anthropic": "ANTHROPIC_API_KEY",
        }
        key = os.environ.get(env_map.get(provider, "OPENAI_API_KEY"), "")
        if not key:
            raise RuntimeError(
                f"API key not found for provider '{provider}'. "
                f"Set {env_map.get(provider, 'OPENAI_API_KEY')} or use OfflineScientistBackend."
            )
        return key

    @staticmethod
    def _default_model(provider: str) -> str:
        defaults = {
            "gemini": "gemini-2.5-pro",
            "openai": "gpt-4o",
            "anthropic": "claude-3-5-sonnet-latest",
        }
        return defaults.get(provider, "gpt-4o")

    def _build_user_prompt(
        self,
        task_name: str,
        task_description: str,
        entrypoint: str,
        history: List[IWSPTrial],
        iteration: int,
    ) -> str:
        lines = [
            f"# Task: {task_name} (Iteration {iteration})",
            f"## Specification\n{task_description}",
            f"## Required Entrypoint\nDefine a Python function `{entrypoint}`.",
        ]
        if history:
            lines.append("\n## Previous Validation Trials")
            for t in history:
                status = f"Score={t.val_score:.4f}" if not t.error else f"Error={t.error}"
                lines.append(
                    f"### Trial {t.iteration} ({status})\n"
                    f"Hypothesis: {t.hypothesis}\n"
                    f"Metrics: {json.dumps(t.metrics)}\n"
                    f"```python\n{t.code}\n```"
                )
            lines.append(
                "\nAnalyze the flaws or bottlenecks in prior trials and write an improved, "
                "fully transparent weight-space program."
            )
        return "\n".join(lines)

    def propose_next_program(
        self,
        task_name: str,
        task_description: str,
        entrypoint: str,
        history: List[IWSPTrial],
        iteration: int,
    ) -> Tuple[str, str]:
        user_prompt = self._build_user_prompt(
            task_name, task_description, entrypoint, history, iteration
        )
        raw_response = self._call_api(user_prompt)
        return self.parse_response(raw_response)

    def _call_api(self, user_prompt: str) -> str:
        if self.provider == "openai":
            url = "https://api.openai.com/v1/chat/completions"
            payload = {
                "model": self.model,
                "temperature": self.temperature,
                "messages": [
                    {"role": "system", "content": self.SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
            }
            headers = {
                "Content-Type": "application/json",
                "Authorization": f"Bearer {self.api_key}",
            }
            req = urllib.request.Request(
                url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST"
            )
            with urllib.request.urlopen(req, timeout=60) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return data["choices"][0]["message"]["content"]

        elif self.provider == "anthropic":
            url = "https://api.anthropic.com/v1/messages"
            payload = {
                "model": self.model,
                "max_tokens": 4096,
                "temperature": self.temperature,
                "system": self.SYSTEM_PROMPT,
                "messages": [{"role": "user", "content": user_prompt}],
            }
            headers = {
                "Content-Type": "application/json",
                "x-api-key": self.api_key,
                "anthropic-version": "2023-06-01",
            }
            req = urllib.request.Request(
                url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST"
            )
            with urllib.request.urlopen(req, timeout=60) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return data["content"][0]["text"]

        elif self.provider == "gemini":
            url = (
                f"https://generativelanguage.googleapis.com/v1beta/models/"
                f"{self.model}:generateContent?key={self.api_key}"
            )
            payload = {
                "systemInstruction": {"parts": [{"text": self.SYSTEM_PROMPT}]},
                "contents": [{"role": "user", "parts": [{"text": user_prompt}]}],
                "generationConfig": {"temperature": self.temperature},
            }
            headers = {"Content-Type": "application/json"}
            req = urllib.request.Request(
                url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST"
            )
            with urllib.request.urlopen(req, timeout=60) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return data["candidates"][0]["content"]["parts"][0]["text"]

        raise ValueError(f"Unsupported LLM provider: {self.provider}")

    @staticmethod
    def parse_response(text: str) -> Tuple[str, str]:
        """Extract `(hypothesis, code)` from the LLM response."""
        hyp_match = re.search(r"HYPOTHESIS:\s*(.+?)(?:\n```|\n\n|$)", text, re.DOTALL)
        hypothesis = (
            hyp_match.group(1).strip().replace("\n", " ")
            if hyp_match
            else "Iterative weight-space refinement"
        )
        code_match = re.search(r"```(?:python)?\s*\n(.*?)```", text, re.DOTALL)
        if code_match:
            code = code_match.group(1).strip()
        else:
            code = text.strip()
        return hypothesis, code


class IWSPLoop:
    """
    Main Interpretable Weight-Space Programming (iWSP) Runner.

    Coordinates the LLM Scientist agent, the code execution sandbox, and the validation
    evaluator over `max_iterations` trials.
    """

    def __init__(
        self,
        backend: LLMBackend,
        sandbox: Optional[SandboxExecutor] = None,
        max_iterations: int = 3,
        target_score: float = 1.0,
    ) -> None:
        self.backend = backend
        self.sandbox = sandbox or SandboxExecutor()
        self.max_iterations = max_iterations
        self.target_score = target_score

    def run(
        self,
        task_name: str,
        domain: str,
        task_description: str,
        evaluator_fn: Callable[[Callable[..., Any]], Tuple[float, Dict[str, Any], str, Any]],
        entrypoint: str = "build_model",
    ) -> IWSPHarvester:
        """
        Execute the iWSP discovery loop.

        `evaluator_fn(entrypoint_fn)` must return:
            `(val_score, metrics_dict, interpretation_summary, compiled_artifact)`
        """
        history: List[IWSPTrial] = []
        best_trial: Optional[IWSPTrial] = None
        best_artifact: Any = None
        best_score = float("-inf")

        for iteration in range(1, self.max_iterations + 1):
            t0 = time.perf_counter()
            hypothesis, code = self.backend.propose_next_program(
                task_name=task_name,
                task_description=task_description,
                entrypoint=entrypoint,
                history=history,
                iteration=iteration,
            )

            try:
                fn, _ = self.sandbox.execute_and_extract(code, entrypoint=entrypoint)
                score, metrics, interp_summary, artifact = evaluator_fn(fn)
                elapsed_ms = (time.perf_counter() - t0) * 1000.0
                is_best = score > best_score
                trial = IWSPTrial(
                    iteration=iteration,
                    hypothesis=hypothesis,
                    code=code,
                    val_score=score,
                    metrics=metrics,
                    interpretation_summary=interp_summary,
                    error=None,
                    elapsed_ms=elapsed_ms,
                    is_best=is_best,
                )
                if is_best:
                    for prev in history:
                        prev.is_best = False
                    best_score = score
                    best_trial = trial
                    best_artifact = artifact
            except Exception as exc:
                elapsed_ms = (time.perf_counter() - t0) * 1000.0
                trial = IWSPTrial(
                    iteration=iteration,
                    hypothesis=hypothesis,
                    code=code,
                    val_score=0.0,
                    metrics={},
                    interpretation_summary="",
                    error=f"{type(exc).__name__}: {exc}",
                    elapsed_ms=elapsed_ms,
                    is_best=False,
                )

            history.append(trial)
            if best_trial is not None and best_score >= self.target_score:
                break

        return IWSPHarvester(
            task_name=task_name,
            domain=domain,
            best_trial=best_trial,
            history=history,
            compiled_artifact=best_artifact,
        )
